package main

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

// generateUnit produces the systemd unit file content for a compose service.
func generateUnit(info *ComposeInfo, composeDir string) string {
	var b strings.Builder

	filename := filepath.Base(info.SourcePath)

	b.WriteString("# Generated by hitch-generator\n")
	b.WriteString(fmt.Sprintf("# Source: %s\n", info.SourcePath))
	b.WriteString("\n")
	b.WriteString("[Unit]\n")
	b.WriteString(fmt.Sprintf("Description=Hitch: %s\n", info.Name))
	b.WriteString("After=network-online.target\n")
	b.WriteString("Requires=network-online.target\n")
	b.WriteString("\n")
	b.WriteString("[Service]\n")
	b.WriteString("Type=oneshot\n")
	b.WriteString("RemainAfterExit=yes\n")
	b.WriteString(fmt.Sprintf("WorkingDirectory=%s\n", composeDir))

	// ExecStartPre for each external network.
	if len(info.ExternalNetworks) > 0 {
		// Sort for deterministic output.
		nets := make([]string, len(info.ExternalNetworks))
		copy(nets, info.ExternalNetworks)
		sort.Strings(nets)

		for _, net := range nets {
			b.WriteString(fmt.Sprintf(
				"ExecStartPre=/bin/sh -c '/usr/bin/podman network exists %s || /usr/bin/podman network create %s'\n",
				net, net,
			))
		}
	}

	b.WriteString(fmt.Sprintf("ExecStart=/usr/bin/podman compose -f %s up -d\n", filename))
	b.WriteString(fmt.Sprintf("ExecStop=/usr/bin/podman compose -f %s down\n", filename))
	b.WriteString(fmt.Sprintf("ExecReload=/usr/bin/podman compose -f %s up -d --force-recreate\n", filename))
	b.WriteString("Restart=on-failure\n")
	b.WriteString("TimeoutStartSec=120\n")

	return b.String()
}
