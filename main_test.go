func TestGeneratorIntegration(t *testing.T) {
	// Set up a temp compose directory with sample files.
	composeDir := t.TempDir()
	outputDir := t.TempDir()

	// Write a compose file with name and external networks.
	authentik := `name: authentik
services:
  server:
    image: ghcr.io/goauthentik/server:latest
networks:
  backend:
    external: true
`
	if err := os.WriteFile(filepath.Join(composeDir, "authentik.yml"), []byte(authentik), 0644); err != nil {
		t.Fatal(err)
	}

	// Write a compose file without a name field (fallback to filename).
	pihole := `services:
  pihole:
    image: pihole/pihole:latest
`
	if err := os.WriteFile(filepath.Join(composeDir, "pihole.yaml"), []byte(pihole), 0644); err != nil {
		t.Fatal(err)
	}

	// Run the generator.
	if err := run(composeDir, outputDir); err != nil {
		t.Fatalf("run() failed: %v", err)
	}

	// --- Verify authentik.service ---
	authentikUnit := filepath.Join(outputDir, "authentik.service")
	data, err := os.ReadFile(authentikUnit)
	if err != nil {
		t.Fatalf("authentik.service not created: %v", err)
	}
	content := string(data)

	// Check required fields.
	checks := []string{
		"# Generated by hitch-generator",
		"# Source: " + filepath.Join(composeDir, "authentik.yml"),
		"Description=Hitch: authentik",
		"Type=oneshot",
		"RemainAfterExit=yes",
		"WorkingDirectory=" + composeDir,
		"ExecStartPre=/bin/sh -c '/usr/bin/podman network exists backend || /usr/bin/podman network create backend'",
		"ExecStart=/usr/bin/podman compose -f authentik.yml up -d",
		"ExecStop=/usr/bin/podman compose -f authentik.yml down",
		"ExecReload=/usr/bin/podman compose -f authentik.yml up -d --force-recreate",
		"Restart=on-failure",
		"TimeoutStartSec=120",
	}
	for _, check := range checks {
		if !strings.Contains(content, check) {
			t.Errorf("authentik.service missing: %q\n\nGot:\n%s", check, content)
		}
	}
	if strings.Contains(content, "network-online.target") {
		t.Errorf("authentik.service should not depend on the system network-online.target in the user manager:\n%s", content)
	}

	// --- Verify pihole.service ---
	piholeUnit := filepath.Join(outputDir, "pihole.service")
	data, err = os.ReadFile(piholeUnit)
	if err != nil {
		t.Fatalf("pihole.service not created: %v", err)
	}
	piholeContent := string(data)

	if !strings.Contains(piholeContent, "Description=Hitch: pihole") {
		t.Errorf("pihole.service should use filename as name, got:\n%s", piholeContent)
	}
	// pihole has no external networks — no ExecStartPre expected.
	if strings.Contains(piholeContent, "ExecStartPre") {
		t.Errorf("pihole.service should not have ExecStartPre (no external networks)")
	}

	// --- Verify default.target.wants symlinks ---
	wantsDir := filepath.Join(outputDir, "default.target.wants")
	info, err := os.Lstat(filepath.Join(wantsDir, "authentik.service"))
	if err != nil {
		t.Fatalf("authentik.service symlink missing: %v", err)
	}
	if info.Mode()&os.ModeSymlink == 0 {
		t.Error("authentik.service in wants dir is not a symlink")
	}

	target, err := os.Readlink(filepath.Join(wantsDir, "authentik.service"))
	if err != nil {
		t.Fatal(err)
	}
	if target != "../authentik.service" {
		t.Errorf("symlink target = %q, want %q", target, "../authentik.service")
	}

	info, err = os.Lstat(filepath.Join(wantsDir, "pihole.service"))
	if err != nil {
		t.Fatalf("pihole.service symlink missing: %v", err)
	}
	if info.Mode()&os.ModeSymlink == 0 {
		t.Error("pihole.service in wants dir is not a symlink")
	}
}

func TestEmptyComposeDir(t *testing.T) {
	composeDir := t.TempDir()
	outputDir := t.TempDir()

	// Should succeed with no files.
	if err := run(composeDir, outputDir); err != nil {
		t.Fatalf("run() failed on empty dir: %v", err)
	}

	// Output dir should be empty (no wants dir created).
	entries, _ := os.ReadDir(outputDir)
	if len(entries) != 0 {
		t.Errorf("expected empty output dir, got %d entries", len(entries))
	}
}

func TestNonExistentComposeDir(t *testing.T) {
	outputDir := t.TempDir()

	// Non-existent compose dir should not be an error (just no output).
	if err := run("/nonexistent/path/compose", outputDir); err != nil {
		t.Fatalf("run() should not fail for non-existent compose dir: %v", err)
	}
}

func TestMultipleExternalNetworks(t *testing.T) {
	composeDir := t.TempDir()
	outputDir := t.TempDir()

	multi := `name: multi
services:
  app:
    image: nginx:latest
networks:
  frontend:
    external: true
  backend:
    external: true
  internal: {}
`
	if err := os.WriteFile(filepath.Join(composeDir, "multi.yml"), []byte(multi), 0644); err != nil {
		t.Fatal(err)
	}

	if err := run(composeDir, outputDir); err != nil {
		t.Fatalf("run() failed: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(outputDir, "multi.service"))
	if err != nil {
		t.Fatal(err)
	}
	content := string(data)

	// Should have ExecStartPre for backend and frontend (sorted), but not internal.
	if !strings.Contains(content, "podman network exists backend || /usr/bin/podman network create backend") {
		t.Error("missing ExecStartPre for backend")
	}
	if !strings.Contains(content, "podman network exists frontend || /usr/bin/podman network create frontend") {
		t.Error("missing ExecStartPre for frontend")
	}
	if strings.Contains(content, "internal") {
		t.Error("should not create ExecStartPre for non-external network 'internal'")
	}
}
